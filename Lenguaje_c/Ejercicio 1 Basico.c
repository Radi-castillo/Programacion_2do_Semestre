#include <stdio.h>
  
int main() {
  printf("¡Hola, mundo!\n");
  return 0;
}

/* 
Línea 1: #include <stdio.h> - Incluye la biblioteca estándar de entrada/salida necesaria para usar printf
Línea 3: int main() { - Función principal, punto de entrada del programa, retorna un entero
Línea 4: printf("¡Hola, mundo!\n"); - Imprime el texto en pantalla, \n es salto de línea
Línea 5: return 0; - Retorna 0 al sistema operativo indicando ejecución exitosa
Línea 6: } - Cierra el bloque de la función main
*/